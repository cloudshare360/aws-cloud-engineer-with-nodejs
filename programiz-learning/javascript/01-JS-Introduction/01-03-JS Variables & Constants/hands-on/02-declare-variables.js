// 02-declare-variables.js
// In JavaScript, we use the var or let keywords to declare variables.
// 'age' is declared with var (function-scoped).
var age;
// 'name' is declared with let (block-scoped).
let name;

// Display the declared variables (both are undefined at this point)
console.log(age); // Output: undefined
console.log(name); // Output: undefined