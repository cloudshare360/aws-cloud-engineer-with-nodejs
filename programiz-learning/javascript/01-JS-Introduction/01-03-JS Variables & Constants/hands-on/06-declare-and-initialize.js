// 06-declare-and-initialize.js
// You can declare and initialize a variable in a single statement.
// declare variable num1 and assign 5 to it
let num1 = 5;

// declare variable num2 and assign 6 to it
let num2 = 6;

// Display both variables
console.log(num1); // Output: 5
console.log(num2); // Output: 6