// 10-valid-variable-names.js
// Rules for naming JavaScript variables:
// Variable names must start with a letter, underscore _, or dollar sign $.
// valid
let message = "hello";
let _message = "hello";
let $message = "hello";

// Display all valid variable names
console.log(message); // Output: hello
console.log(_message); // Output: hello
console.log($message); // Output: hello